// Regenerates src/sim/trigTable.ts. The table is committed so the sim never calls Math.sin at runtime.
import { writeFileSync } from 'node:fs';
const v = [];
for (let d = 0; d <= 90; d++) v.push(Math.round(Math.sin((d * Math.PI) / 180) * 10000));
let s = '// Generated by scripts/gen-trig.mjs — do not edit. sin(d°) * 10000 for d = 0..90.\nexport const SIN_Q: readonly number[] = [\n';
for (let i = 0; i < v.length; i += 13) s += '  ' + v.slice(i, i + 13).join(', ') + ',\n';
s += '];\n';
writeFileSync(new URL('../src/sim/trigTable.ts', import.meta.url), s);
